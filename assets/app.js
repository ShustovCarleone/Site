const hlsPlayers = []
function initializeHlsPlayers() {
  document.querySelectorAll('video[data-hls]:not([data-hls-ready])').forEach((video) => {
    const source = video.dataset.hls
    if (!source) return

    if (video.canPlayType('application/vnd.apple.mpegurl')) {
      video.src = source
      video.dataset.hlsReady = 'true'
      return
    }

    if (window.Hls?.isSupported()) {
      const player = new window.Hls({ enableWorker: true })
      player.loadSource(source)
      player.attachMedia(video)
      hlsPlayers.push(player)
      video.dataset.hlsReady = 'true'
    }
  })
}

